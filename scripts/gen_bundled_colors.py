#!/usr/bin/env python3
"""Generate include/bundled_colors.h from data/material_database.json.

The firmware unions these product colours (and their English names) into the board's DB on every
Update DB, so a colour the printer's factory file lacks (Hyper PC Transparent #FFFFFF00) still
reaches the picker without a uploadfs. Re-run after replacing data/material_database.json:

    python3 scripts/gen_bundled_colors.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "material_database.json"
OUT = ROOT / "include" / "bundled_colors.h"


def main() -> None:
    db = json.loads(SRC.read_text(encoding="utf-8"))
    out = {}
    for entry in db["result"]["list"]:
        base = entry["base"]
        pid = base.get("id", "")
        if not pid or pid in out:  # first entry per id, as FilamentDB does
            continue
        colors = [c for c in base.get("colors") or [] if isinstance(c, str) and c.startswith("#")]
        if not colors:
            continue
        wanted = {c.upper() for c in colors}
        mix = [
            {"colorEn": m.get("colorEn", ""), "hexValue": m["hexValue"]}
            for m in base.get("mixColorInfoList") or []
            if isinstance(m.get("hexValue"), str) and m["hexValue"].upper() in wanted
        ]
        out[pid] = {"colors": colors, "mixColorInfoList": mix}

    payload = json.dumps(out, separators=(",", ":"), ensure_ascii=True)
    assert ")BC\"" not in payload
    OUT.write_text(
        "#pragma once\n"
        "/**\n"
        " * @file bundled_colors.h\n"
        " * @brief Product colours + names from data/material_database.json, unioned into the board's\n"
        " *        DB by Update DB (material_db_merge.h). GENERATED by scripts/gen_bundled_colors.py:\n"
        " *        don't edit, re-run it.\n"
        " */\n"
        f"// {len(out)} profiles, {len(payload)} bytes\n"
        f'static const char BUNDLED_COLORS_JSON[] = R"BC({payload})BC";\n',
        encoding="utf-8",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(out)} profiles, {len(payload)} bytes")


if __name__ == "__main__":
    main()
